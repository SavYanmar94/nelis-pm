#!/bin/bash
set -euo pipefail
for value in "${PROJECT_DB_PASSWORD}" "${RESOURCE_DB_PASSWORD}"; do
  if [[ ! "$value" =~ ^[A-Za-z0-9_]{8,64}$ ]]; then
    echo "Le password demo devono avere 8-64 caratteri alfanumerici o underscore" >&2
    exit 1
  fi
done
sqlplus -s "system/${ORACLE_PWD}@//localhost:1521/FREEPDB1" <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM dba_users WHERE username = 'NELIS_PROJECT';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER NELIS_PROJECT IDENTIFIED BY "${PROJECT_DB_PASSWORD}"';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER NELIS_PROJECT IDENTIFIED BY "${PROJECT_DB_PASSWORD}"';
  END IF;
  SELECT COUNT(*) INTO n FROM dba_users WHERE username = 'NELIS_RESOURCE';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER NELIS_RESOURCE IDENTIFIED BY "${RESOURCE_DB_PASSWORD}"';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER NELIS_RESOURCE IDENTIFIED BY "${RESOURCE_DB_PASSWORD}"';
  END IF;
END;
/
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, UNLIMITED TABLESPACE TO NELIS_PROJECT;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, UNLIMITED TABLESPACE TO NELIS_RESOURCE;
EXIT
SQL
